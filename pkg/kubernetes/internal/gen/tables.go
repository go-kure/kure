// tableData is everything the three table artifacts are rendered from, derived
// once so the Go values, the JSON and the site page cannot disagree.
type tableData struct {
	Kinds  []kindRow
	Fields []fieldRow
}

// tableJSON is the shape of the committed JSON artifact. JSON has no comment
// syntax, so the provenance the Go and Markdown artifacts carry in a header
// comment has to be a field here — otherwise the one artifact a reader is most
// likely to open in isolation is the one that never says it is generated.
type tableJSON struct {
	Generated string     `json:"_generated"`
	Kinds     []kindRow  `json:"kinds"`
	Fields    []fieldRow `json:"fields"`
}

// jsonProvenance is the JSON artifact's DO NOT EDIT.
const jsonProvenance = "Generated by pkg/kubernetes/internal/gen from the registered scheme and the pinned upstream module sources; DO NOT EDIT."

// kindRow is one registered kind. The JSON names match pkg/kubernetes.KindInfo's
// fields so a consumer reading either sees the same vocabulary.
type kindRow struct {
	Group         string `json:"group"`
	Version       string `json:"version"`
	Kind          string `json:"kind"`
	GoType        string `json:"goType"`
	ImportPath    string `json:"importPath"`
	Module        string `json:"module"`
	ModuleVersion string `json:"moduleVersion"`
	Namespaced    bool   `json:"namespaced"`
	ScopeSource   string `json:"scopeSource"`
}

// fieldRow is one field carrying a maturity signal.
type fieldRow struct {
	ImportPath    string   `json:"importPath"`
	TypeName      string   `json:"typeName"`
	Field         string   `json:"field"`
	GoField       string   `json:"goField"`
	Gates         []string `json:"gates,omitempty"`
	Stability     string   `json:"stability,omitempty"`
	Module        string   `json:"module"`
	ModuleVersion string   `json:"moduleVersion"`
}

// deriveTables resolves every kind's scope from the pinned upstream sources and
// walks the type graph for the maturity table. The upstream load happens once:
// it is the most expensive step, and both halves need the same map.
func deriveTables(all []kinds.Kind) (tableData, error) {
	types, err := kinds.LoadTypes(all)
	if err != nil {
		return tableData{}, err
	}
	resolved, err := kinds.ResolveScopes(all, types)
	if err != nil {
		return tableData{}, err
	}
	scopes := map[string]kinds.DerivedScope{}
	for _, d := range resolved {
		scopes[d.Key] = d
	}

	data := tableData{}
	roots := make([]maturity.Root, 0, len(all))
	for _, k := range all {
		d, ok := scopes[k.Key()]
		if !ok {
			return tableData{}, errors.Errorf("gen: no scope resolved for %s", k.Key())
		}
		// kinds.Registered() already derives Namespaced from this same
		// resolution, so comparing the two here would assert nothing —
		// the antecedent would imply the consequent. The guard that a
		// derivation regression must trip lives where it can still fail: the
		// frozen cluster-scoped fixture in internal/kinds' own tests.
		if namespaced := d.Scope != markers.ScopeCluster; namespaced != k.Namespaced {
			return tableData{}, errors.Errorf("gen: %s: derived namespaced=%v, kinds.Registered says %v; the two must come from one resolution", k.Key(), namespaced, k.Namespaced)
		}
		data.Kinds = append(data.Kinds, kindRow{
			Group:         k.GVK.Group,
			Version:       k.GVK.Version,
			Kind:          k.GVK.Kind,
			GoType:        k.TypeName,
			ImportPath:    k.ImportPath,
			Module:        d.Module,
			ModuleVersion: d.Version,
			Namespaced:    k.Namespaced,
			ScopeSource:   string(d.Source),
		})
		roots = append(roots, maturity.Root{ImportPath: k.ImportPath, TypeName: k.TypeName})
	}

	entries, err := maturity.Walk(roots, types)
	if err != nil {
		return tableData{}, err
	}
	for _, e := range entries {
		data.Fields = append(data.Fields, fieldRow{
			ImportPath:    e.ImportPath,
			TypeName:      e.TypeName,
			Field:         e.Field,
			GoField:       e.GoField,
			Gates:         e.Gates,
			Stability:     string(e.Stability),
			Module:        e.Module,
			ModuleVersion: e.Version,
		})
	}
	sort.Slice(data.Kinds, func(i, j int) bool {
		a, b := data.Kinds[i], data.Kinds[j]
		if a.Group != b.Group {
			return a.Group < b.Group
		}
		if a.Kind != b.Kind {
			return a.Kind < b.Kind
		}
		return a.Version < b.Version
	})
	return data, nil
}

// renderTablesGo emits the committed Go values.
func renderTablesGo(data tableData) ([]byte, error) {
	var b strings.Builder
	b.WriteString(tablesHeader)
	b.WriteString("package kubernetes\n\n")
	b.WriteString("// kinds is every object kind registered in the scheme, with the pinned module\n// its Go type came from and the scope derived from that module. Unexported: the\n// lookups read it on every call, so a consumer holding the slice itself could\n// change what every later caller is told. [Kinds] returns a copy.\nvar kinds = []KindInfo{\n")
	for _, k := range data.Kinds {
		fmt.Fprintf(&b, "\t{Group: %q, Version: %q, Kind: %q, GoType: %q, ImportPath: %q, Module: %q, ModuleVersion: %q, Namespaced: %v, ScopeSource: %q},\n",
			k.Group, k.Version, k.Kind, k.GoType, k.ImportPath, k.Module, k.ModuleVersion, k.Namespaced, k.ScopeSource)
	}
	b.WriteString("}\n\n")
	b.WriteString("// fieldMaturities is every construction-side field of a registered kind that\n// the pinned sources gate or document as less than stable. Status types are not\n// walked; see the package README for why. Unexported for the same reason as\n// [kinds], and each row carries a Gates slice that shares backing memory with\n// this one until copied; [FieldMaturities] returns a copy of both.\nvar fieldMaturities = []FieldMaturity{\n")
	for _, f := range data.Fields {
		fmt.Fprintf(&b, "\t{ImportPath: %q, TypeName: %q, Field: %q, GoField: %q, Gates: %s, Stability: %s, Module: %q, ModuleVersion: %q},\n",
			f.ImportPath, f.TypeName, f.Field, f.GoField, goStrings(f.Gates), maturityConst(f.Stability), f.Module, f.ModuleVersion)
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}

// goStrings renders a []string literal, or nil when there is nothing to say —
// an empty slice literal would claim a value the source does not carry.
func goStrings(values []string) string {
	if len(values) == 0 {
		return "nil"
	}
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = fmt.Sprintf("%q", v)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

// maturityConst names the exported constant rather than repeating its value, so
// the generated file breaks if a constant is renamed instead of silently
// carrying a string nothing declares.
func maturityConst(stability string) string {
	switch stability {
	case "alpha":
		return "MaturityAlpha"
	case "beta":
		return "MaturityBeta"
	case "deprecated":
		return "MaturityDeprecated"
	default:
		return "MaturityStable"
	}
}

// renderTablesJSON emits the machine-readable artifact. Indented and
// newline-terminated: it is committed and read as a diff on a bump PR, which is
// the whole reason it exists.
func renderTablesJSON(data tableData) ([]byte, error) {
	out, err := json.MarshalIndent(tableJSON{
		Generated: jsonProvenance,
		Kinds:     data.Kinds,
		Fields:    data.Fields,
	}, "", "  ")
	if err != nil {
		return nil, errors.Wrap(err, "gen: rendering the JSON table")
	}
	return append(out, '\n'), nil
}

// renderTablesDoc emits the site page. Markdown, not the JSON: extra_mounts
// prepends front matter to whatever it mounts, so only a document survives
// being mounted.
func renderTablesDoc(data tableData) []byte {
	var b strings.Builder
	b.WriteString("<!-- Code generated by pkg/kubernetes/internal/gen; DO NOT EDIT. -->\n")
	b.WriteString("<!-- Source: the registered scheme and the pinned upstream module sources. -->\n\n")
	b.WriteString("# Supported kinds and field maturity\n\n")
	b.WriteString("Generated from the modules this build pins. Every row names the module and\nversion it was read from, so a table entry is always traceable to a pin.\n\n")

	fmt.Fprintf(&b, "## Kinds (%d)\n\n", len(data.Kinds))
	b.WriteString("`Scope from` is what stated the scope: the kind's own `+kubebuilder:resource`\nmarker, the `CustomResourceDefinition` its module ships, or the built-in table\nfor the kinds whose scope the API server defines.\n\n")
	b.WriteString("| API version | Kind | Scope | Scope from | Go type | Module |\n")
	b.WriteString("|---|---|---|---|---|---|\n")
	for _, k := range data.Kinds {
		scope := "Cluster"
		if k.Namespaced {
			scope = "Namespaced"
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | `%s` | `%s` | `%s@%s` |\n",
			apiVersion(k.Group, k.Version), k.Kind, scope, k.ScopeSource, k.GoType, k.Module, k.ModuleVersion)
	}

	fmt.Fprintf(&b, "\n## Field maturity (%d)\n\n", len(data.Fields))
	b.WriteString("kure neither warns nor filters on any of this: it reports, and a consumer with\ncluster knowledge decides. For built-in types the API server does not reject a\nfield whose feature gate is disabled — it clears the field and admits the\nobject, so the manifest reads as applied and is not.\n\n")
	b.WriteString("Status types are excluded: their fields are reported by the cluster, never set\nby a caller.\n\n")
	b.WriteString("| Type | Field | Stability | Feature gates | Module |\n")
	b.WriteString("|---|---|---|---|---|\n")
	for _, f := range data.Fields {
		stability := f.Stability
		if stability == "" {
			stability = "stable"
		}
		gates := "—"
		if len(f.Gates) > 0 {
			gates = "`" + strings.Join(f.Gates, "`, `") + "`"
		}
		fmt.Fprintf(&b, "| `%s.%s` | `%s` | %s | %s | `%s@%s` |\n",
			shortImport(f.ImportPath), f.TypeName, f.Field, stability, gates, f.Module, f.ModuleVersion)
	}
	return []byte(b.String())
}

func apiVersion(group, version string) string {
	if group == "" {
		return version
	}
	return group + "/" + version
}

// shortImport keeps the table readable: the last two path segments identify a
// package unambiguously across the modules kure pins.
func shortImport(path string) string {
	parts := strings.Split(path, "/")
	if len(parts) <= 2 {
		return path
	}
	return strings.Join(parts[len(parts)-2:], "/")
}
