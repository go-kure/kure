// Command gen emits the per-kind constructor wrappers under pkg/kubernetes and
// the kinds registry the identity test walks, from the registered scheme and
// the scope table in internal/kinds.
//
//	go run ./pkg/kubernetes/internal/gen            # write the files
//	go run ./pkg/kubernetes/internal/gen -check     # exit 1 when any file is stale
//
// scripts/gen-builders.sh wraps both modes; make gen-builders / check-builders
// and the CI validate job call the script.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/go-kure/kure/pkg/kubernetes/internal/kinds"
)

const (
	header         = "// Code generated by pkg/kubernetes/internal/gen; DO NOT EDIT.\n// Source: the registered scheme (RegisterSchemes) and the scope table in internal/kinds.\n\n"
	createFile     = "zz_generated_create.go"
	createTestFile = "zz_generated_create_test.go"
	registryFile   = "zz_generated_kinds_test.go"
	rootImport     = "github.com/go-kure/kure/pkg/kubernetes"
	rootGoPackage  = "kubernetes"
)

func main() {
	os.Exit(run(os.Args[1:], os.Stderr))
}

// run parses args, renders every generated file and either writes them or,
// with -check, reports the stale ones. It returns the process exit code.
func run(args []string, stderr io.Writer) int {
	fs := flag.NewFlagSet("gen", flag.ContinueOnError)
	fs.SetOutput(stderr)
	check := fs.Bool("check", false, "verify the generated files are current instead of writing them")
	root := fs.String("root", "pkg/kubernetes", "directory holding the kubernetes builder packages")
	if err := fs.Parse(args); err != nil {
		return 2
	}

	files, err := render(*root)
	if err != nil {
		_, _ = fmt.Fprintln(stderr, "gen:", err)
		return 1
	}
	orphans, err := findOrphans(*root, files)
	if err != nil {
		_, _ = fmt.Fprintln(stderr, "gen:", err)
		return 1
	}
	if *check {
		stale := 0
		for _, path := range sortedKeys(files) {
			have, readErr := os.ReadFile(path) //nolint:gosec // paths are derived from the scheme, not from input
			if readErr != nil || !bytes.Equal(have, files[path]) {
				_, _ = fmt.Fprintf(stderr, "gen: %s is stale (run scripts/gen-builders.sh generate)\n", path)
				stale++
			}
		}
		for _, path := range orphans {
			_, _ = fmt.Fprintf(stderr, "gen: %s is orphaned, no registered kind routes to its package (run scripts/gen-builders.sh generate)\n", path)
			stale++
		}
		if stale > 0 {
			return 1
		}
		return 0
	}
	for _, path := range orphans {
		if err := os.Remove(path); err != nil {
			_, _ = fmt.Fprintln(stderr, "gen:", err)
			return 1
		}
	}
	for _, path := range sortedKeys(files) {
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			_, _ = fmt.Fprintln(stderr, "gen:", err)
			return 1
		}
		if err := os.WriteFile(path, files[path], 0o600); err != nil {
			_, _ = fmt.Fprintln(stderr, "gen:", err)
			return 1
		}
	}
	return 0
}

// render returns every generated file, keyed by path, formatted.
func render(root string) (map[string][]byte, error) {
	all, err := kinds.Registered()
	if err != nil {
		return nil, err
	}
	byPackage := map[string][]kinds.Kind{}
	for _, k := range all {
		byPackage[k.Package] = append(byPackage[k.Package], k)
	}
	aliases, err := importAliases(all)
	if err != nil {
		return nil, err
	}

	files := map[string][]byte{}
	for pkg, ks := range byPackage {
		if err := checkUniqueWrappers(pkg, ks); err != nil {
			return nil, err
		}
		src, err := renderCreateFile(pkg, ks, aliases)
		if err != nil {
			return nil, err
		}
		files[filepath.Join(root, pkg, createFile)] = src
		test, err := renderCreateTestFile(pkg, ks)
		if err != nil {
			return nil, err
		}
		files[filepath.Join(root, pkg, createTestFile)] = test
	}
	src, err := renderRegistry(all)
	if err != nil {
		return nil, err
	}
	files[filepath.Join(root, registryFile)] = src
	return files, nil
}

// findOrphans walks root for generated files that no current package renders:
// the leftovers of a package whose every kind left the scheme. A missing root
// is not an error (nothing can be orphaned there).
func findOrphans(root string, files map[string][]byte) ([]string, error) {
	generated := map[string]bool{createFile: true, createTestFile: true, registryFile: true}
	var orphans []string
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, walkErr error) error {
		if walkErr != nil {
			if path == root && os.IsNotExist(walkErr) {
				return filepath.SkipAll
			}
			return walkErr
		}
		if d.IsDir() || !generated[d.Name()] {
			return nil
		}
		if _, rendered := files[path]; !rendered {
			orphans = append(orphans, path)
		}
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("gen: scan %s for orphaned files: %w", root, err)
	}
	sort.Strings(orphans)
	return orphans, nil
}

func wrapperName(k kinds.Kind) string { return "Create" + k.GVK.Kind }

func checkUniqueWrappers(pkg string, ks []kinds.Kind) error {
	seen := map[string]kinds.Kind{}
	for _, k := range ks {
		name := wrapperName(k)
		if prev, dup := seen[name]; dup {
			return fmt.Errorf("gen: %s would be generated twice in package %q (%s and %s); give one a version-qualified name", name, pkg, prev.GVK, k.GVK)
		}
		seen[name] = k
	}
	return nil
}

// importAliases assigns a unique import alias to every upstream package.
var versionSegment = regexp.MustCompile(`^v\d`)

func importAliases(all []kinds.Kind) (map[string]string, error) {
	aliases := map[string]string{}
	used := map[string]string{}
	for _, k := range all {
		if _, done := aliases[k.ImportPath]; done {
			continue
		}
		alias := aliasFor(k.ImportPath)
		if other, clash := used[alias]; clash && other != k.ImportPath {
			return nil, fmt.Errorf("gen: import alias %q for %s collides with %s", alias, k.ImportPath, other)
		}
		aliases[k.ImportPath] = alias
		used[alias] = k.ImportPath
	}
	return aliases, nil
}

// aliasFor derives an alias like corev1, certmanagerv1, sourcewatcherv2v1beta1
// from the meaningful trailing segments of an import path.
func aliasFor(importPath string) string {
	var segs []string
	for _, s := range strings.Split(importPath, "/") {
		switch s {
		case "pkg", "api", "apis":
			continue
		}
		segs = append(segs, s)
	}
	// keep the last two segments, or three when the penultimate is a version too
	n := 2
	if len(segs) >= 3 && versionSegment.MatchString(segs[len(segs)-2]) {
		n = 3
	}
	if len(segs) > n {
		segs = segs[len(segs)-n:]
	}
	clean := regexp.MustCompile(`[^a-z0-9]`)
	return clean.ReplaceAllString(strings.ToLower(strings.Join(segs, "")), "")
}

func renderCreateFile(pkg string, ks []kinds.Kind, aliases map[string]string) ([]byte, error) {
	goPkg := rootGoPackage
	createRef := "Create"
	if pkg != "" {
		goPkg = pkg
		createRef = rootGoPackage + ".Create"
	}
	imports := map[string]bool{}
	for _, k := range ks {
		imports[k.ImportPath] = true
	}
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "package %s\n\nimport (\n", goPkg)
	for _, p := range sortedKeys(imports) {
		fmt.Fprintf(&b, "\t%s %q\n", aliases[p], p)
	}
	if pkg != "" {
		fmt.Fprintf(&b, "\n\t%q\n", rootImport)
	}
	b.WriteString(")\n")
	for _, k := range ks {
		typ := aliases[k.ImportPath] + "." + k.TypeName
		if k.Namespaced {
			fmt.Fprintf(&b, "\n// %s returns a %s %s carrying TypeMeta and identity only.\nfunc %s(name, namespace string) *%s {\n\treturn %s[%s](name, namespace)\n}\n",
				wrapperName(k), k.GVK.GroupVersion(), k.GVK.Kind, wrapperName(k), typ, createRef, typ)
		} else {
			fmt.Fprintf(&b, "\n// %s returns a cluster-scoped %s %s carrying TypeMeta and identity only.\nfunc %s(name string) *%s {\n\treturn %s[%s](name, \"\")\n}\n",
				wrapperName(k), k.GVK.GroupVersion(), k.GVK.Kind, wrapperName(k), typ, createRef, typ)
		}
	}
	return format.Source([]byte(b.String()))
}

// renderCreateTestFile emits one in-package test per package that calls every
// wrapper once and checks the identity it returns, so each package's own
// coverage exercises its generated constructors.
func renderCreateTestFile(pkg string, ks []kinds.Kind) ([]byte, error) {
	goPkg := rootGoPackage
	if pkg != "" {
		goPkg = pkg
	}
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "package %s\n\nimport (\n\t\"testing\"\n\n\t\"sigs.k8s.io/controller-runtime/pkg/client\"\n)\n\n", goPkg)
	b.WriteString("func TestGeneratedConstructors(t *testing.T) {\n\tcases := []struct {\n\t\tkind       string\n\t\tnamespaced bool\n\t\tobj        client.Object\n\t}{\n")
	for _, k := range ks {
		if k.Namespaced {
			fmt.Fprintf(&b, "\t\t{%q, true, %s(\"name\", \"ns\")},\n", k.GVK.Kind, wrapperName(k))
		} else {
			fmt.Fprintf(&b, "\t\t{%q, false, %s(\"name\")},\n", k.GVK.Kind, wrapperName(k))
		}
	}
	b.WriteString("\t}\n\tfor _, c := range cases {\n\t\tt.Run(c.kind, func(t *testing.T) {\n")
	b.WriteString("\t\t\tif got := c.obj.GetObjectKind().GroupVersionKind().Kind; got != c.kind {\n\t\t\t\tt.Errorf(\"kind = %q, want %q\", got, c.kind)\n\t\t\t}\n")
	b.WriteString("\t\t\twantNS := \"\"\n\t\t\tif c.namespaced {\n\t\t\t\twantNS = \"ns\"\n\t\t\t}\n")
	b.WriteString("\t\t\tif c.obj.GetName() != \"name\" || c.obj.GetNamespace() != wantNS {\n\t\t\t\tt.Errorf(\"identity = %s/%s, want %s/name\", c.obj.GetNamespace(), c.obj.GetName(), wantNS)\n\t\t\t}\n")
	b.WriteString("\t\t})\n\t}\n}\n")
	return format.Source([]byte(b.String()))
}

func renderRegistry(all []kinds.Kind) ([]byte, error) {
	pkgs := map[string]bool{}
	for _, k := range all {
		pkgs[k.Package] = true
	}
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package kubernetes_test\n\nimport (\n\t\"k8s.io/apimachinery/pkg/runtime/schema\"\n\t\"sigs.k8s.io/controller-runtime/pkg/client\"\n\n")
	for _, p := range sortedKeys(pkgs) {
		if p == "" {
			fmt.Fprintf(&b, "\t%q\n", rootImport)
		} else {
			fmt.Fprintf(&b, "\t%q\n", rootImport+"/"+p)
		}
	}
	b.WriteString(")\n\n")
	b.WriteString("// generatedKind pairs a registered GVK with its generated constructor wrapper.\ntype generatedKind struct {\n\tGVK        schema.GroupVersionKind\n\tNamespaced bool\n\tCreate     func(name, namespace string) client.Object\n}\n\n")
	b.WriteString("// generatedKinds lists every generated wrapper; the identity test walks the\n// scheme and fails on any registered kind missing here.\nvar generatedKinds = []generatedKind{\n")
	for _, k := range all {
		goPkg := rootGoPackage
		if k.Package != "" {
			goPkg = k.Package
		}
		call := goPkg + "." + wrapperName(k) + "(name, namespace)"
		params := "name, namespace string"
		if !k.Namespaced {
			call = goPkg + "." + wrapperName(k) + "(name)"
			params = "name, _ string"
		}
		fmt.Fprintf(&b, "\t{GVK: schema.GroupVersionKind{Group: %q, Version: %q, Kind: %q}, Namespaced: %v, Create: func(%s) client.Object { return %s }},\n",
			k.GVK.Group, k.GVK.Version, k.GVK.Kind, k.Namespaced, params, call)
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
